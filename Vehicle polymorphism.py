class BMW:

    def engine(self):
        print("BMW uses a V8 engine")

    def horsepower(self):
        print("BMW produces 500 horsepower")

    def mileage(self):
        print("BMW has a mileage of 25 MPG")

class Audi:

    def engine(self):
        print("Audi uses a V6 engine")

    def horsepower(self):
        print("Audi produces 400 horsepower")

    def mileage(self):
        print("Audi has a mileage of 30 MPG")
